; \1 selects byte mapping; \2 selects runtime strides.
C2P4_LINES macro
	movem.l	d2-d7/a2-a6,-(sp)
	ifne	\1
	move.l	64(sp),a3
	endif
	move.l	56(sp),d0
	move.l	52(sp),a4
	move.l	48(sp),a5
	move.l	60(sp),d1
	move.l	d0,a6
	tst.l	d1
	beq.w	.noline
	ifne	\2
	mulu.w	66+4*\1(sp),d1						; low word of source stride, before srcEnd push
	else
	mulu.w	#320,d1
	endif
	add.l	a4,d1
	move.l	d1,-(sp)
	move.l	#$00ff00ff,d5
	move.l	#$55555555,d6
	ifne	\1
	moveq.l	#0,d4
	endif
.nextline:
	move.l	a4,a0
	move.l	a5,a1
	lea		(a0,a6.l),a2
	C2P4_PIXELS \1
	ifne	\2
	adda.l	68+4*\1(sp),a4						; source stride, after srcEnd push
	adda.l	72+4*\1(sp),a5						; destination stride
	else
	lea		320(a4),a4							; next chunky scanline
	lea		160(a5),a5							; next planar scanline
	endif
	cmpa.l	(sp),a4
	bne.w	.nextline

	addq.l	#4,sp								; drop srcEnd
.noline:
	movem.l	(sp)+,d2-d7/a2-a6
	rts
	endm

